typedef unsigned long long U;
static S run(int k, S a, S b)
{
    switch (k) {
    case OP_ADD: return a + b;
    case OP_SUB: return a - b;
    case OP_MUL: return a * b;
    case OP_DIV: return (b && !(a == (S)0x8000000000000000ULL && b == -1)) ? a / b : 0;
    case OP_MOD: return (b && !(a == (S)0x8000000000000000ULL && b == -1)) ? a % b : 0;
    case OP_UDIV: return (U)b ? (S)((U)a / (U)b) : 0;
    case OP_UMOD: return (U)b ? (S)((U)a % (U)b) : 0;
    case OP_SHL: return a << (b & 63);
    case OP_SHR: return a >> (b & 63);
    case OP_USHR: return (S)((U)a >> (b & 63));
    case OP_LT: return a < b;
    case OP_LE: return a <= b;
    case OP_GT: return a > b;
    case OP_GE: return a >= b;
    case OP_ULT: return (U)a < (U)b;
    case OP_NOT: return !a;
    }
    return 0;
}

static void test_ll_table(void)
{
    static const char *const nm[NOPS] = {
        "add", "sub", "mul", "div", "mod", "udiv", "umod", "shl", "shr", "ushr", "lt", "le", "gt", "ge", "ult", "not"
    };
    int k, i, j;
    for (k = 0; k < NOPS; k++)
        for (i = 0; i < N; i++)
            for (j = 0; j < N; j++)
                Assert(run(k, V[i], V[j]) == E[k][i * N + j], nm[k]);
}

static S fp_sum(int tag, S a, S b) { return a * 3 + b + tag; }
static S (*fp_call)(int, S, S) = fp_sum;

/* A 64-bit argument through a function pointer is pushed under the int */
static void test_ll_fnptr(void)
{
    S r = fp_call(5, 0x0102030405060708LL, 0x1111111122222222LL);
    Assert(r == 0x14171a1d3134373fLL, "long long args through a function pointer");
}

int main(int argc, char *argv[])
{
    suite_setup("64-bit arithmetic table");
    suite_add_test(test_ll_table);
    suite_add_test(test_ll_fnptr);
    return suite_run();
}
