#!/usr/bin/env python3
"""Generate asm7801_ops.h, the uPD7801 opcode table, from MAME's unidasm (env UNIDASM, default ~/emu/mame0283-arm64/unidasm).

The instruction set will not change, so the header is checked in and this is run only if it is lost:  gen_ops.py > asm7801_ops.h
Each entry is the disassembly of one opcode (or prefix and byte) with the immediate operand shown as #, its bytes, and the size of that operand.
"""
import os, re, subprocess, sys, tempfile

UNIDASM = os.environ.get('UNIDASM', os.path.expanduser('~/emu/mame0283-arm64/unidasm'))
PREFIX = [0x48, 0x4c, 0x4d, 0x60, 0x64, 0x70, 0x74]

def disasm(f, bs):
    open(f, 'wb').write(bytes(bs) + bytes([0x11, 0x22, 0x33]))      # (the operand bytes show up as $11 and $2211)
    out = subprocess.run([UNIDASM, f, '-arch', 'upd7801', '-basepc', '0x100', '-norawbytes', '-count', '1'],
                         capture_output=True, text=True).stdout
    return out.strip().splitlines()[0]

def norm(s):
    s = s.split(':', 1)[1].strip() if re.match(r'^[0-9a-f]+:', s) else s
    return re.sub(r'\s+', ' ', s.strip().upper())

ops = {}                                    # pattern -> (bytes, kind): the first opcode with a pattern wins
with tempfile.TemporaryDirectory() as d:
    f = os.path.join(d, 't.bin')
    cands = []
    for op in range(256):
        if op in PREFIX:
            cands += [(op, b) for b in range(256)]
        else:
            cands.append((op,))
    for bs in cands:
        s = norm(disasm(f, bs))
        if 'ILLEGAL' in s:
            continue
        kind = 2 if '$2211' in s else 1 if '$11' in s else 0
        s = s.replace('$2211', '#').replace('$11', '#')
        ops.setdefault(s, (bs, kind))

print('/* generated by gen_ops.py from unidasm -arch upd7801: pattern, opcode bytes, and the operand after them (0 none, 1 byte, 2 word) */')
print('typedef struct { const char *pat; unsigned char len, kind, b[2]; } op7801;')
print('static const op7801 ops7801[] = {')
for p, (bs, kind) in ops.items():
    print('    { "%s", %d, %d, { 0x%02x, 0x%02x } },' % (p, len(bs), kind, bs[0], bs[1] if len(bs) > 1 else 0))
print('};')
