#!/usr/bin/env python3
"""Assemble the all-RAM console's sub-CPU program and its loader (sub.s.in, loader.s.in) with support/upd7801/asm7801.py.

  build.py      -> sub.bin (page 1), sub2.bin (the rest, a multiple of 8 bytes), loader.bin, sub.inc (the command bytes for z80asm)
The outputs are checked in, so building z88dk does not need Python.
"""
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(here, '..', '..', '..', '..', '..', 'support', 'upd7801'))
from asm7801 import Asm

BASE = 0x9000                   # the program: spare VRAM, one page for the JB dispatch (the commands' entry points)
BASE2 = 0x9100                  # the rest: the commands' bodies, which the takeover sends
LOADER = 0x3A60                 # where the ROM's "run" command ($6B) executes: blue plane, cell (4, 21)
a = Asm(os.path.join(here, '..', '..', '..', '..', '..', 'support', 'upd7801', 'asm7801_ops.json'))
src = open(os.path.join(here, 'sub.s.in')).read().replace('@BASE@', '$%04X' % BASE).replace('@PAGE@', '$%02X' % (BASE >> 8)).replace('@BASE2@', '$%04X' % BASE2)
both, labels = a.assemble(src, BASE)
sub, sub2 = both[:labels['P1End'] - BASE], both[256:]
assert len(sub) <= 256 and labels['KeysBody'] == BASE2
sub2 = sub2.ljust(-(-len(sub2) // 8) * 8, b'\0')                  # (sent 8 bytes at a time)
open(os.path.join(here, 'sub.bin'), 'wb').write(sub)
open(os.path.join(here, 'sub2.bin'), 'wb').write(sub2)
lsrc = open(os.path.join(here, 'loader.s.in')).read()
lsrc = lsrc.replace('@BASE@', '$%04X' % BASE).replace('@SUBLEN@', str(len(sub))).replace('@SUBLEN1@', str(len(sub) - 1))
loader, _ = a.assemble(lsrc, LOADER)
assert len(loader) <= 40, len(loader)       # five "define character" blocks
open(os.path.join(here, 'loader.bin'), 'wb').write(loader.ljust(40, b'\0'))
with open(os.path.join(here, 'sub.inc'), 'w') as f:
    f.write('; generated by build.py\nDEFC SUB_SIZE = %d\nDEFC SUB2_SIZE = %d\n' % (len(sub), len(sub2)))
    for n in ('Addr', 'Pat', 'Glyph', 'Text', 'Fill', 'Scroll', 'Keys', 'Pix', 'Point', 'Line'):
        f.write('DEFC SUB_%s = $%02X\n' % (n.upper(), labels[n] & 255))
print('sub program: page 1 %d of 256 bytes, the rest %d, loader %d of 40' % (len(sub), len(sub2), len(loader)))
